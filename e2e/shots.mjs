// Screenshots for the README: node shots.mjs <out dir> [port]
import { chromium } from "@playwright/test";
const out = process.argv[2];
const base = `http://127.0.0.1:${process.argv[3] ?? "8000"}`;
const MK01 = "p=MK01&cap=1.5&int=0.15&seed=5000&lam=3&m=ppo_bc_ppo_g@0,fix3_g,acak_g,aor";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1500, height: 920 } });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
const shot = async (name, url, wait, full = false) => {
  if (url) await page.goto(base + url);
  if (wait) await page.waitForSelector(wait, { timeout: 240000 });
  await page.waitForTimeout(700);
  await page.screenshot({ path: `${out}/${name}.png`, fullPage: full });
};
