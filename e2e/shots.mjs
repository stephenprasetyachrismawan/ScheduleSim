import { chromium } from "@playwright/test";
const out = process.argv[2];
const base = "http://127.0.0.1:8000";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1500, height: 920 } });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
const shot = async (name, url, wait) => {
  await page.goto(base + url);
  if (wait) await page.waitForSelector(wait, { timeout: 60000 });
  await page.waitForTimeout(600);
  await page.screenshot({ path: `${out}/${name}.png` });
};
await shot("01_projects", "/", ".pcard");
await shot("02_board", "/proyek/MK01?view=board", ".card");
await shot("03_list", "/proyek/MK01?view=list", "table.grid");
await shot("04_gantt", "/proyek/MK01?view=gantt", ".gbar");
await shot("05_form", "/proyek/MK01?view=form&issue=MK01-12", ".sheet");
await page.goto(base + "/simulasi?project=MK01");
await page.waitForSelector("text=Jalankan");
await page.click("button:has-text('Jalankan')");
await page.waitForSelector(".ev", { timeout: 180000 });
await page.waitForTimeout(800);
await page.click(".ev >> nth=2");
await page.waitForTimeout(900);
await page.screenshot({ path: `${out}/06_sim_gantt.png` });
await page.click("button[title='Board (kanban)']");
await page.waitForTimeout(700);
await page.screenshot({ path: `${out}/07_sim_board.png` });
await shot("08_results", "/hasil-uji", "figure");
await shot("09_method", "/metode", "table.grid");
console.log("errors:", JSON.stringify(errors.slice(0, 10)));
await browser.close();
